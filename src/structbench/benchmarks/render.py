_MARKER = "<!-- generated by tools/gen_benchmark_docs.py; do not edit by hand -->"

# Honest-not-silent (ADR-0033/0046): the shared heading/label suffix that
# flags a provisional result everywhere it can be mistaken for blessed —
# _baseline_line and _baseline_details. (The leaderboard's Method cell uses the
# italic ` *(provisional)*` variant so it reads inside a table row.)
_PROVISIONAL_TAG = " (provisional)"


def _yesno(flag: bool) -> str:
    return "yes" if flag else "no"


def _fmt_value(value: float) -> str:
    return f"{value:g}"


def _registry_name(spec: BenchmarkSpec) -> str | None:
    """The registry key owning ``spec``, matched by unique card name.

    Landing pages live at ``docs/benchmarks/<registry-name>.md``; the index
    links to them. Matching by ``card.name`` (unique per benchmark) keeps
    working for ``dataclasses.replace``-d specs used in tests, which no longer
    share object identity with the registry's ``SPEC``.
    """
    from .registry import available_benchmarks, get_benchmark

    for name in available_benchmarks():
        if get_benchmark(name).card.name == spec.card.name:
            return name
    return None


def _page_asset(path: str) -> str:
    """Rewrite a repo-relative asset path for a page at ``docs/benchmarks/``.

    A committed figure path like ``assets/foo.png`` becomes ``../../assets/foo.png``
    so the link resolves from the two-deep page location; absolute URLs pass
    through unchanged.
    """
    if path.startswith(("http://", "https://")):
        return path
    return f"../../{path}"


def _task_lines(c: BenchmarkCard) -> list[str]:
    """The shared 'Task' section (archive README and landing page)."""
    return [
        "## Task",
        "",
        f"{c.task}. Auxiliary target: `{c.aux_field}` ({c.aux_unit}). "
        "Models advance the particle state autoregressively from a short "
        "ground-truth prefix and are scored on the full predicted rollout.",
    ]


def _eval_lines(c: BenchmarkCard, *, fold_rationale: bool = False) -> list[str]:
    """The shared 'Evaluation criteria' section (archive README and page).

    ``fold_rationale`` moves the long ``protocol_rationale`` into a collapsed
    ``<details>`` block after the metrics (used by the landing page, where the
    full paragraph would otherwise dominate the section) instead of an inline
    bullet. The text is rendered verbatim either way — single source, no
    rewrite.
    """
    lines = [
        "## Evaluation criteria",
        "",
        f"- Protocol (benchmark-owned, ADR-0032, ADR-0035): {c.input_frames} "
        f"input frames, horizon {c.horizon}, scored at {c.eval_times} output times.",
    ]
    if not fold_rationale:
        lines.append(f"- Protocol rationale: {c.protocol_rationale}")
    lines += [
        f"- Metrics: headline is the pooled space+time relative L2 "
        f"(displacement + {c.aux_field}); also reported are position/"
        f"{c.aux_field} RMSE (physical units) and one-step RMSE, plus the "
        f"quantities of interest below.",
        f"- Quantities of interest: {', '.join(c.qois)}.",
    ]
    if fold_rationale:
        lines += [
            "",
            "<details>",
            "<summary>Protocol rationale — the ground-truth timeline analysis "
            "behind these values (ADR-0032 §5)</summary>",
            "",
            c.protocol_rationale,
            "",
            "</details>",
        ]
    return lines


def _partition_metrics(
    names: list[str],
) -> tuple[list[str], list[str], list[str]]:
    """Split metric keys into ``(rel_l2, rmse, qoi)`` groups, each preserving
    the caller's first-seen order.

    ADR-0055 (amended 2026-08-15; pooled follow-up 2026-08-16): relative L2 is
    the headline metric — a single pooled space+time number per quantity. It
    leads; physical-unit RMSE is the secondary group; ``qoi_*`` keys are the
    separate engineering axis. A key is relative-L2 iff it contains ``rel_l2``
    (covers ``rollout_rel_l2_displacement`` and any unit-suffixed registry
    variant); QoI iff it starts ``qoi_``; RMSE otherwise. (A per-frame-mean
    relative-L2 secondary existed briefly but was dropped 2026-08-16 — it blew
    up on zero-start aux fields and matched no reported convention.)
    """
    rel_l2 = [m for m in names if "rel_l2" in m]
    qoi = [m for m in names if m.startswith("qoi_")]
    rmse = [m for m in names if "rel_l2" not in m and not m.startswith("qoi_")]
    return rel_l2, rmse, qoi


def _headline_metric(metrics: Mapping[str, float]) -> str:
    """The metric key quoted first in the docs-index one-liner: the pooled
    rollout relative-L2 displacement if present (ADR-0055 headline), else any
    relative-L2 key, else the first metric (pre-amendment behaviour, and the
    fallback for runs whose relative-L2 keys are not yet populated)."""
    rel_keys = [m for m in metrics if "rel_l2" in m]
    if rel_keys:
        rollout_disp = (m for m in rel_keys if "rollout" in m and "disp" in m)
        return next(rollout_disp, rel_keys[0])
    return next(iter(metrics))


def _baseline_line(spec: BenchmarkSpec) -> str:
    """Compact one-line results summary for the docs index (ADR-0033)."""
    if not spec.results:
        return "*no official baseline yet*"
    parts = []
    for r in spec.results:
        headline = ""
        for split in spec.splits:
            if split in r.metrics:
                key = _headline_metric(r.metrics[split])
                headline = f": {split} {key} {_fmt_value(r.metrics[split][key])}"
                break
        # Honest-not-silent (ADR-0033/0046): a provisional entry is tagged
        # here too, so the index never quietly reads as blessed.
        tag = _PROVISIONAL_TAG if r.provisional else ""
        parts.append(
            f"{r.label} ({r.family}, {r.run_date}, `{r.run_commit}`){tag}{headline}"
        )
    return "; ".join(parts)


def _quickstart_family(spec: BenchmarkSpec) -> tuple[str, str]:
    """The Quickstart's model family and its selection provenance (ADR-0046).

    Selection chain: the first blessed result's family (declaration order);
    else the first result's family, whether or not it is provisional; else
    ``spec.quickstart_family``. A provisional entry listed before a later
    blessed one still loses to the blessed one, since ``blessed_results``
    already preserves declaration order among blessed entries only.

    Returns
    -------
    tuple of str, str
        ``(family, provenance)`` with ``provenance`` one of ``"blessed"``,
        ``"provisional"``, or ``"default"``.
    """
    if spec.blessed_results:
        return spec.blessed_results[0].family, "blessed"
    if spec.results:
        return spec.results[0].family, "provisional"
    return spec.quickstart_family, "default"


def _col_label(split: str, key: str) -> str:
    """Compact ``split·quantity`` header for one leaderboard column.

    Strips the scheme/aggregation prefixes and metric suffixes so the header
    reads as the physical quantity with a parenthesised unit, keeping only what
    distinguishes the column: ``rollout_rel_l2_disp`` @ ``test_interp`` ->
    ``interp·disp``; ``rollout_pos_rmse_mm`` -> ``interp·pos (mm)``;
    ``rollout_vm_rmse_mpa`` -> ``interp·vm (MPa)``; ``qoi_final_length_mae_mm``
    -> ``interp·final_length (mm)``; ``qoi_t_peak_vm_mae_ms`` ->
    ``interp·t_peak_vm (ms)``.
    """
    s = split.replace("test_", "")
    k = (
        key.replace("rollout_", "")
        .replace("one_step_", "1s·")
        .replace("qoi_", "")
        .replace("rel_l2_", "")
        .replace("_rmse", "")
        .replace("_mae", "")
    )
    for suffix, unit in (("_mm", " (mm)"), ("_mpa", " (MPa)"), ("_ms", " (ms)")):
        if k.endswith(suffix):
            k = k[: -len(suffix)] + unit
            break
    return f"{s}·{k}"


#: Leaderboard metric tiers, in render order, aligned with
#: :func:`_partition_metrics`'s ``(rel_l2, rmse, qoi)`` split (ADR-0055).
_LEADERBOARD_TIERS: tuple[str, ...] = (
    "Headline — pooled relative L2 (↓ better)",
    "Trajectory error — RMSE",
    "Quantities of interest (MAE)",
)


def _leaderboard(spec: BenchmarkSpec) -> list[str]:
    """The ranked cross-method leaderboard (ADR-0041 clause 4, ADR-0046,
    ADR-0055).

    One row per ``spec.results`` entry, in registry declaration order (the
    maintainer's chosen method order). Three metric tiers — the pooled
    relative-L2 headline, physical-unit RMSE, and the engineering QoIs
    (ADR-0055) — partitioned by :func:`_partition_metrics`; an empty tier is
    skipped. The headline tier spans every split; the RMSE and QoI tiers are
    trimmed to the in-distribution ``test_interp`` split, and RMSE drops the
    one-step columns, to keep the tables readable (the full numbers stay in the
    registry and run data).

    Within a tier the columns are ``(split, key)`` pairs kept only where some
    result carries them; headers use :func:`_col_label`; the first two columns
    are ``Method`` and ``Scheme``, missing cells ``—``. Called by both
    :func:`render_benchmark_page` and :func:`render_archive_readme`, immediately
    before ``## Baseline details``. Its empty-state placeholder is deliberately
    distinct from :func:`_baseline_details`'s "no official baseline yet".
    """
    lines = ["## Leaderboard", ""]
    if not spec.results:
        lines.append(
            "*No results yet — method entries land here as runs are "
            "recorded (blessed or provisional).*"
        )
        return lines
    # Global first-seen metric order: results in declaration order, each
    # result's splits in card order (mirrors _baseline_line's per-result rule).
    metric_order: list[str] = []
    for r in spec.results:
        for split in spec.splits:
            for metric in r.metrics.get(split, {}):
                if metric not in metric_order:
                    metric_order.append(metric)
    rel_l2, rmse, qoi = _partition_metrics(metric_order)
    # Trim (2026-08-16): headline spans all splits; RMSE and QoI show
    # the in-distribution split only, and RMSE drops the one-step diagnostics.
    rmse = [k for k in rmse if "one_step" not in k]
    # The trimmed tiers show the in-distribution scored split: prefer
    # ``test_interp`` where the benchmark splits it out, else the first split
    # that actually carries metrics (e.g. a single ``test`` split on
    # DeformingPlate) - never ``train``/``val``, which are unscored.
    scored = [s for s in spec.splits if any(s in r.metrics for r in spec.results)]
    interp = ["test_interp"] if "test_interp" in scored else scored[:1]
    trimmed = f"`{interp[0]}`" if interp else "the in-distribution"
    lines += [
        "The headline metric is the pooled space+time relative L2 (↓ lower is "
        "better); the Scheme column is the prediction scheme. RMSE and "
        f"quantities of interest are shown for the in-distribution {trimmed} "
        "split.",
        "",
    ]
    tiers = (
        (_LEADERBOARD_TIERS[0], rel_l2, list(spec.splits)),
        (_LEADERBOARD_TIERS[1], rmse, interp),
        (_LEADERBOARD_TIERS[2], qoi, interp),
    )
    for title, tier_keys, tier_splits in tiers:
        if not tier_keys:
            continue
        columns = [
            (split, key)
            for split in tier_splits
            for key in tier_keys
            if any(key in r.metrics.get(split, {}) for r in spec.results)
        ]
        if not columns:
            continue
        header = ["Method", "Scheme"] + [_col_label(s, k) for s, k in columns]
        lines.append(f"_{title}_")
        lines.append("")
        lines.append("| " + " | ".join(header) + " |")
        lines.append("|---|" + "---|" * (len(header) - 1))
        for r in spec.results:
            label = r.label + (" *(training)*" if r.pending else "")
            cells = [label, r.scheme or "—"]
            for split, key in columns:
                vals = r.metrics.get(split, {})
                cells.append(_fmt_value(vals[key]) if key in vals else "—")
            lines.append("| " + " | ".join(cells) + " |")
        lines.append("")
    lines.pop()  # drop the trailing blank left by the last tier
    if any(r.pending for r in spec.results):
        lines += [
            "",
            "_Rows marked (training) are baselines whose run is still in "
            "progress; their numbers land when it completes._",
        ]
    return lines


def _baseline_details(spec: BenchmarkSpec) -> list[str]:
    """Per-result provenance / reproduction block (ADR-0033/0037/0046).

    The numbers now live in the leaderboard; this section carries only what
    reproduces and traces a result: a bold heading (label, family, run date,
    commit, and the checkpoint pointer with its private-archive marker) and the
    free-text notes beneath it. A provisional entry's heading gains
    :data:`_PROVISIONAL_TAG` so it never reads as a blessed "number to beat"
    (honest-not-silent). Keeps the empty-state placeholder.
    """
    lines = ["## Baseline details", ""]
    if not spec.results:
        lines.append(
            "*No official baseline yet — the reference run's metrics land here.*"
        )
        return lines
    for r in spec.results:
        if r.checkpoint:
            # Private archive-relative pointers carry an explicit marker until
            # rewritten to a public URL (ADR-0037) — honest rather than silent.
            published = r.checkpoint.startswith(("http://", "https://"))
            marker = "" if published else " — private archive; publication parked"
            suffix = f", checkpoint: `{r.checkpoint}`{marker}"
        else:
            suffix = ""
        heading = (
            f"**{r.label}** ({r.family}, {r.run_date}, commit `{r.run_commit}`{suffix})"
        )
        lines.append(heading)
        if r.notes:
            lines.extend(["", f"*{r.notes}*"])
        lines.append("")
    return lines[:-1]


# Presentation order for the index: the constitutive ladder (linear elastic →
# elastoplastic → fracture → 3D hyperelastic contact), matching the root
# README's Benchmarks table. Keyed by card name; unlisted benchmarks follow,
# sorted by name.
PRESENTATION_ORDER = (
    "Wave1D-Propagation",
    "Taylor2D-Impact",
    "NotchBeam2D-Impact",
    "DeformingPlate",
)


def render_index(specs: list[BenchmarkSpec]) -> str:
    """The full ``docs/benchmarks.md`` content for the given specs.

    Parameters
    ----------
    specs : list of BenchmarkSpec
        Benchmarks to render; presented in :data:`PRESENTATION_ORDER`
        (unlisted benchmarks follow, sorted by card name), regardless of
        input order.

    Returns
    -------
    str
        Markdown document containing the generation marker, a 9-column
        comparison table, and one ## section per benchmark.
    """
    rank = {name: i for i, name in enumerate(PRESENTATION_ORDER)}
    specs = sorted(
        specs,
        key=lambda s: (rank.get(s.card.name, len(PRESENTATION_ORDER)), s.card.name),
    )
    lines = [
        _MARKER,
        "",
        "# Benchmarks",
        "",
        "One row per benchmark; see each section for the full card.",
        "Note: `sph/stress` and `sph/strain` are full 6-component Voigt "
        "tensors; each benchmark's scalar target (von Mises, axial, principal) "
        "is derived from them by the loader — see the Aux target column.",
        "",
        "| Benchmark | Solver | Discretisation | Erosion | Loading | Cases "
        "| Particles | Frames | Aux target |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for spec in specs:
        c = spec.card
        lines.append(
            f"| {c.name} | {c.solver} | {c.discretisation} | {_yesno(c.erosion)} "
            f"| {c.loading} | {c.n_cases} | {c.particles_per_case} "
            f"| {c.n_frames} | {c.aux_field} ({c.aux_unit}) |"
        )
    for spec in specs:
        lines.extend(["", *_section(spec)])
    return "\n".join(lines) + "\n"


def _section(spec: BenchmarkSpec) -> list[str]:
    c = spec.card
    splits = ", ".join(f"{name} {n}" for name, n in c.splits.items())
    name = _registry_name(spec)
    lines = [
        f"## {c.name} (v{c.version})",
        "",
        c.description,
        "",
        f"- **Task**: {c.task}",
        f"- **Materials**: {', '.join(c.materials)}",
        f"- **Geometry**: {c.geometry}; source units {c.source_units}",
        f"- **Splits**: {splits}",
        f"- **Protocol** (ADR-0032, ADR-0035): {c.input_frames} input frames, "
        f"horizon {c.horizon}, scored at {c.eval_times} output times. "
        f"*Rationale*: {c.protocol_rationale}",
        f"- **QoIs**: {', '.join(c.qois)}",
        f"- **Baseline**: {_baseline_line(spec)}",
        f"- **Fields**: {', '.join(c.fields)}",
        f"- **Provenance**: {c.provenance}",
        f"- **License**: {c.data_license}",
    ]
    if name is not None:
        lines.append(
            f"- **Full page**: [docs/benchmarks/{name}.md](benchmarks/{name}.md)"
        )
    return lines


def _stress_derivation_line(c: BenchmarkCard) -> str:
    """How the archive's stress/aux field relates to what's stored on disk.

    SPH benchmarks store 6-component Voigt stress/strain tensors and derive
    scalar targets (e.g. von Mises) at load time. Mesh/FEM (and, absent a
    precedent otherwise, any non-SPH) benchmarks store the scalar nodal
    field directly — the mesh-aware loader reads it verbatim, no Voigt
    reconstruction (ADR-0043 §5).
    """
    if c.discretisation == "SPH":
        return (
            "`sph/stress` and `sph/strain` are 6-component Voigt tensors; "
            "scalar targets are loader-derived (see the card's aux field)."
        )
    return (
        f"`node/{c.aux_field}` is stored directly as a nodal scalar field; "
        "the mesh-aware loader reads it verbatim (no Voigt tensor reconstruction)."
    )


def _references(spec: BenchmarkSpec) -> list[str]:
    """A ``## References`` section citing each method's paper.

    Collects the ``reference`` string from each result (ADR-0033), de-duplicated
    by citation — methods that share a paper are listed once under both labels —
    in declaration order. Returns ``[]`` (section omitted) when no result carries
    a reference, so benchmarks without cited baselines render unchanged.
    """
    by_ref: dict[str, list[str]] = {}
    order: list[str] = []
    for r in spec.results:
        ref = r.reference.strip()
        if not ref:
            continue
        if ref not in by_ref:
            by_ref[ref] = []
            order.append(ref)
        by_ref[ref].append(r.label)
    if not order:
        return []
    lines = ["## References", ""]
    lines += [f"- **{' / '.join(by_ref[ref])}** — {ref}" for ref in order]
    return lines


