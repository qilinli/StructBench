_SENSITIVITY_TITLE = "Sensitivity — the gradient family (ADR-0076)"


def _sensitivity_tier(spec: BenchmarkSpec, lead: list[str]) -> list[str]:
    """The gradient family's rows (ADR-0076 clauses 4 and 7): one line per
    result and quantity of interest, read from the result's
    :data:`~structbench.benchmarks.registry.GRADIENT_GROUP` metrics.

    Columns: the pooled relative L2 of the model's sensitivity against the
    reference central differences, the fraction of sign agreements, the
    model's own floor (the disagreement of its two step sizes, on the same
    scale) and the judged count over the scored count. A quantity with no
    judged value shows dashes and its count. ``lead`` is the registry's
    leading header (``Method``, ``Scheme`` and the tier columns in use).
    Empty when the benchmark declares no family or no result reports it.
    """
    family = spec.gradient_family
    if family is None or not any(GRADIENT_GROUP in r.metrics for r in spec.results):
        return []
    header = [*lead, "Quantity", "rel L2", "sign agreement", "own floor"]
    header.append("judged / scored")
    lines = [
        f"_{_SENSITIVITY_TITLE}_",
        "",
        "| " + " | ".join(header) + " |",
        "|---|" + "---|" * (len(header) - 1),
    ]
    show_tier, show_division = "Tier" in lead, "Division" in lead
    for r in spec.results:
        values = r.metrics.get(GRADIENT_GROUP)
        if values is None:
            continue
        for qoi in spec.qois:
            judged = values.get(f"gradient_n_judged_{qoi}")
            if judged is None:
                continue
            reported = values.get(f"gradient_n_reported_{qoi}", 0.0)
            cells = [r.label, r.scheme or "—"]
            if show_tier:
                cells.append(_TIER_LABEL[r.tier])
            if show_division:
                cells.append(r.division)
            cells.append(qoi)
            for kind in ("rel_l2", "sign", "floor"):
                value = values.get(f"gradient_{kind}_{qoi}")
                cells.append("—" if value is None else _fmt_value(value))
            cells.append(f"{int(judged)} / {int(judged + reported)}")
            lines.append("| " + " | ".join(cells) + " |")
    lines += [
        "",
        "_The derivative of each quantity of interest with respect to "
        f"`{family.parameter}`, the model's by central differences of its own "
        "rollouts, against the reference sensitivities and pooled over the "
        "judged values of the scored sets (↓ lower is better; 1 is the error "
        "of predicting no sensitivity). The own floor is the disagreement "
        "between the model's two step sizes on the same scale. A value whose "
        "reference error exceeds half its sensitivity is reported, not "
        "judged._",
    ]
    return lines


def _coverage_tier(spec: BenchmarkSpec) -> list[str]:
    """The ``Headline by coverage bin`` table (ADR-0074 clause 7).

    For every result that carries ``case_metrics``, the mean over the cases
    in each ``(set, coverage bin)`` of the result's headline metric
    (:func:`_headline_metric` of its per-case keys). Columns are the pairs
    some result's cases fall in, in set order then bin order; a result
    without per-case rows renders ``—``. Returns ``[]`` when no result has
    per-case rows or the benchmark cannot compute coverage.
    """
    with_cases = [r for r in spec.results if r.case_metrics]
    if not with_cases:
        return []
    try:
        cov = spec.coverage()
    except ValueError:
        return []
    columns: list[tuple[str, str]] = []
    for split in spec.scored_splits:
        bins: list[str] = []
        for case_id in spec.splits[split]:
            if any(case_id in r.case_metrics for r in with_cases):
                label = coverage_bin(cov[case_id])
                if label not in bins:
                    bins.append(label)
        columns += [(split, b) for b in bins]
    if not columns:
        return []
    header = ["Method", "Scheme"] + [
        f"{s.replace('test_', '')}·{b}" for s, b in columns
    ]
    lines = [
        "_Headline by coverage bin — mean over the cases in each bin_",
        "",
        "| " + " | ".join(header) + " |",
        "|---|" + "---|" * (len(header) - 1),
    ]
    for r in spec.results:
        cells = [r.label, r.scheme or "—"]
        for split, label in columns:
            values = [
                r.case_metrics[c][_headline_metric(r.case_metrics[c])]
                for c in spec.splits[split]
                if c in r.case_metrics and coverage_bin(cov[c]) == label
            ]
            cells.append(_fmt_value(sum(values) / len(values)) if values else "—")
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def _results_registry(spec: BenchmarkSpec) -> list[str]:
    """The cross-method results registry (ADR-0041 clause 4, ADR-0046,
    ADR-0055; unranked and tiered by ADR-0074).

    One row per ``spec.results`` entry, in registration order (the
    maintainer's declaration order; never a rank). The properties block
    leads (ADR-0075 clause 6): its columns are every property the benchmark
    defines (:attr:`BenchmarkSpec.defined_properties`) on the in-distribution
    split, rendered whether or not any result has reported them, plus any
    ``prop_*`` key a result carries; a note under it says what an empty cell
    means. Then three accuracy tiers — the pooled relative-L2 headline,
    physical-unit RMSE, and the engineering QoIs (ADR-0055) — partitioned by
    :func:`_partition_metrics`; an empty accuracy tier is skipped. The
    headline tier spans every split; the RMSE and QoI tiers are trimmed to
    the in-distribution ``test_interp`` split, and RMSE drops the one-step
    columns, to keep the tables readable (the full numbers stay in the
    registry and run data). A last table, the headline by coverage bin,
    renders when a result carries per-case rows (:func:`_coverage_tier`).

    Within a tier the columns are ``(split, key)`` pairs kept only where some
    result carries them; headers use :func:`_col_label`; the first columns are
    ``Method`` and ``Scheme``, then ``Tier`` and ``Division`` when any result
    is external or open (ADR-0074), missing cells ``—``. Called by
    :func:`render_benchmark_page` immediately before ``## Baseline details``.
    Its empty-state placeholder is deliberately distinct from
    :func:`_baseline_details`'s "no official baseline yet".
    """
    lines = ["## Results registry", ""]
    if not spec.results:
        lines.append(
            "*No results yet — method entries land here as runs are "
            "recorded (blessed or provisional).*"
        )
        return lines
    show_tier = any(r.tier != "platform" for r in spec.results)
    show_division = any(r.division != "closed" for r in spec.results)
    # Global first-seen metric order: results in declaration order, each
    # result's splits in card order (mirrors _baseline_line's per-result rule).
    metric_order: list[str] = []
    for r in spec.results:
        for split in spec.splits:
            for metric in r.metrics.get(split, {}):
                if metric not in metric_order:
                    metric_order.append(metric)
    props, rel_l2, rmse, qoi, restart = _partition_metrics(metric_order)
    # ADR-0075 clause 6: the defined properties first, in their order, then
    # any property a result reports beyond them.
    props = list(spec.defined_properties) + [
        k for k in props if k not in spec.defined_properties
    ]
    # Trim (2026-08-16): headline spans all splits; RMSE and QoI show
    # the in-distribution split only, and RMSE drops the one-step diagnostics.
    rmse = [k for k in rmse if "one_step" not in k]
    # The trimmed tiers show the in-distribution scored split: prefer
    # ``test_interp`` where the benchmark splits it out, else the first split
    # that actually carries metrics (e.g. a single ``test`` split on
    # DeformingPlate) - never ``train``/``val``, which are unscored.
    scored = [s for s in spec.splits if any(s in r.metrics for r in spec.results)]
    interp = ["test_interp"] if "test_interp" in scored else scored[:1]
    trimmed = f"`{interp[0]}`" if interp else "the in-distribution"
    lines += [
        "Rows are in registration order and are not ranked (ADR-0074): a result "
        "is read beside the coverage of the set it was scored on (the Scored "
        "sets above) and its properties, which lead (ADR-0075). The headline "
        "metric is the pooled space+time relative L2 (↓ lower is better); the "
        "Scheme column is the prediction scheme. Properties, RMSE and "
        f"quantities of interest are shown for the in-distribution {trimmed} "
        "split.",
        "",
    ]
    # (title, keys, splits, every column shown even when no result carries it)
    tiers = (
        (_REGISTRY_TIERS[0], props, interp, True),
        (_REGISTRY_TIERS[1], rel_l2, list(spec.splits), False),
        (_REGISTRY_TIERS[2], rmse, interp, False),
        (_REGISTRY_TIERS[3], qoi, interp, False),
        (_REGISTRY_TIERS[4], restart, interp, False),
    )
    lead = ["Method", "Scheme"] + (["Tier"] if show_tier else [])
    lead += ["Division"] if show_division else []
    for title, tier_keys, tier_splits, always in tiers:
        # ADR-0076 clause 7: the Sensitivity tier follows the quantities of
        # interest and precedes the restart family. It has its own shape (a
        # line per quantity), so it is not one of the column tiers.
        if title == _REGISTRY_TIERS[4]:
            sensitivity = _sensitivity_tier(spec, lead)
            if sensitivity:
                lines += [*sensitivity, ""]
        if not tier_keys:
            continue
        columns = [
            (split, key)
            for split in tier_splits
            for key in tier_keys
            if always or any(key in r.metrics.get(split, {}) for r in spec.results)
        ]
        if not columns:
            continue
        # ADR-0075 clause 5: the restart tier says what each row restarted from.
        restart_tier = title == _REGISTRY_TIERS[4]
        header = lead + (["Kind"] if restart_tier else [])
        header += [_col_label(s, k) for s, k in columns]
        lines.append(f"_{title}_")
        lines.append("")
        lines.append("| " + " | ".join(header) + " |")
        lines.append("|---|" + "---|" * (len(header) - 1))
        for r in spec.results:
            label = r.label + (" *(training)*" if r.pending else "")
            cells = [label, r.scheme or "—"]
            if show_tier:
                cells.append(_TIER_LABEL[r.tier])
            if show_division:
                cells.append(r.division)
            if restart_tier:
                cells.append(r.restart_kind or "—")
            for split, key in columns:
                # A null is a property undefined on that run (a time-
                # conditioned run's closure, ADR-0054): a dash, like an
                # absent key.
                value = r.metrics.get(split, {}).get(key)
                cells.append("—" if value is None else _fmt_value(value))
            lines.append("| " + " | ".join(cells) + " |")
        if title == _REGISTRY_TIERS[0]:
            lines += ["", _PROPERTIES_NOTE]
        lines.append("")
    by_coverage = _coverage_tier(spec)
    if by_coverage:
        lines += [*by_coverage, ""]
    lines.pop()  # drop the trailing blank left by the last tier
    if any(r.pending for r in spec.results):
        lines += [
            "",
            "_Rows marked (training) are baselines whose run is still in "
            "progress; their numbers land when it completes._",
        ]
    return lines


def _baseline_details(spec: BenchmarkSpec) -> list[str]:
    """Per-result provenance / reproduction block (ADR-0033/0037/0046).

    The numbers now live in the results registry; this section carries only what
    reproduces and traces a result: a bold heading (label, family, run date,
    commit, and the checkpoint pointer with its private-archive marker) and the
    free-text notes beneath it. A provisional entry's heading gains
    :data:`_PROVISIONAL_TAG` so it never reads as a blessed "number to beat"
    (honest-not-silent). Keeps the empty-state placeholder.
    """
    lines = ["## Baseline details", ""]
    if not spec.results:
        lines.append(
            "*No official baseline yet — the reference run's metrics land here.*"
        )
        return lines
    for r in spec.results:
        if r.checkpoint:
            # Private archive-relative pointers carry an explicit marker until
            # rewritten to a public URL (ADR-0037) — honest rather than silent.
            published = r.checkpoint.startswith(("http://", "https://"))
            marker = "" if published else " — private archive; publication parked"
            suffix = f", checkpoint: `{r.checkpoint}`{marker}"
        else:
            suffix = ""
        heading = (
            f"**{r.label}** ({r.family}, {r.run_date}, commit `{r.run_commit}`{suffix})"
        )
        lines.append(heading)
        # ADR-0074: an external or open-division result says so, with its
        # submitter, blind tag and write-up; a platform run adds nothing.
        provenance = []
        if r.tier != "platform":
            provenance.append(f"{_TIER_LABEL[r.tier]} result")
        if r.division != "closed":
            provenance.append(f"{r.division} division ({r.data})")
        if r.blind_tag:
            provenance.append(f"scored under `{r.blind_tag}`")
        if r.submitter:
            provenance.append(f"submitted by {r.submitter}")
        if r.writeup:
            provenance.append(f"write-up <{r.writeup}>")
        if provenance:
            lines.extend(["", "; ".join(provenance) + "."])
        if r.notes:
            lines.extend(["", f"*{r.notes}*"])
        lines.append("")
    return lines[:-1]


