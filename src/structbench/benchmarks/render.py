def _stress_derivation_line(c: BenchmarkCard) -> str:
    """How the archive's stress/aux field relates to what's stored on disk.

    SPH benchmarks store 6-component Voigt stress/strain tensors and derive
    scalar targets (e.g. von Mises) at load time. Mesh/FEM (and, absent a
    precedent otherwise, any non-SPH) benchmarks store the scalar nodal
    field directly — the mesh-aware loader reads it verbatim, no Voigt
    reconstruction (ADR-0043 §5).
    """
    if c.discretisation == "SPH":
        return (
            "`sph/stress` and `sph/strain` are 6-component Voigt tensors; "
            "scalar targets are loader-derived (see the card's aux field)."
        )
    return (
        f"`node/{c.aux_field}` is stored directly as a nodal scalar field; "
        "the mesh-aware loader reads it verbatim (no Voigt tensor reconstruction)."
    )


def _references(spec: BenchmarkSpec) -> list[str]:
    """A ``## References`` section citing each method's paper.

    Collects the ``reference`` string from each result (ADR-0033), de-duplicated
    by citation — methods that share a paper are listed once under both labels —
    in declaration order. Returns ``[]`` (section omitted) when no result carries
    a reference, so benchmarks without cited baselines render unchanged.
    """
    by_ref: dict[str, list[str]] = {}
    order: list[str] = []
    for r in spec.results:
        ref = r.reference.strip()
        if not ref:
            continue
        if ref not in by_ref:
            by_ref[ref] = []
            order.append(ref)
        # A family tabled under several schemes shares one label; repeat it
        # once, not per row ("Transolver", not "Transolver / Transolver").
        if r.label not in by_ref[ref]:
            by_ref[ref].append(r.label)
    if not order:
        return []
    lines = ["## References", ""]
    lines += [f"- **{' / '.join(by_ref[ref])}** — {ref}" for ref in order]
    return lines


