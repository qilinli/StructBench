def _eval_lines(c: BenchmarkCard, *, fold_rationale: bool = False) -> list[str]:
    """The shared 'Evaluation criteria' section (archive README and page).

    ``fold_rationale`` moves the long ``protocol_rationale`` into a collapsed
    ``<details>`` block after the metrics (used by the landing page, where the
    full paragraph would otherwise dominate the section) instead of an inline
    bullet. The text is rendered verbatim either way — single source, no
    rewrite.
    """
    lines = [
        "## Evaluation criteria",
        "",
        f"- Protocol (benchmark-owned, ADR-0032, ADR-0035): {c.input_frames} "
        f"input frames, horizon {c.horizon}, scored at {c.eval_times} output times.",
    ]
    if not fold_rationale:
        lines.append(f"- Protocol rationale: {c.protocol_rationale}")
    lines += [
        f"- Metrics: headline is the pooled space+time relative L2 "
        f"(displacement + {c.aux_field}); also reported are position/"
        f"{c.aux_field} RMSE (physical units) and one-step RMSE, plus the "
        f"quantities of interest below.",
        f"- Quantities of interest: {', '.join(c.qois)}.",
    ]
    if fold_rationale:
        lines += [
            "",
            "<details>",
            "<summary>Protocol rationale — the ground-truth timeline analysis "
            "behind these values (ADR-0032 §5)</summary>",
            "",
            c.protocol_rationale,
            "",
            "</details>",
        ]
    return lines


def _vv_lines(c: BenchmarkCard) -> list[str]:
    """The V&V identity bullets for *Data at a glance* / *Dataset summary*
    (ADR-0065 follow-up 2, plan of 2026-11-08).

    Each bullet renders only when its field is declared, so a card that
    predates the fields renders exactly as before. The parameter space is
    one bullet: design, then the declared box per parameter, the margin
    (or that none is declared) and the categorical levels.
    """
    lines: list[str] = []
    if c.structural_scale:
        lines.append(f"- Structural scale: {c.structural_scale}")
    if c.load_type.strip():
        lines.append(f"- Load type: {c.load_type}")
    if c.autonomy.strip():
        lines.append(f"- Autonomy: {c.autonomy}")
    if c.parameter_space is not None:
        p = c.parameter_space
        parts = [p.design]
        if p.box:
            # A degenerate range is a parameter the design holds fixed — say
            # so, rather than printing "80–80".
            box = "; ".join(
                f"{k} {lo:g} (fixed)" if lo == hi else f"{k} {lo:g}–{hi:g}"
                for k, (lo, hi) in p.box.items()
            )
            parts.append(f"training box: {box}")
        parts.append(
            f"margin: {p.margin}" if p.margin.strip() else "margin: none declared"
        )
        if p.categorical:
            cats = "; ".join(
                f"{k} {{{', '.join(levels)}}}" for k, levels in p.categorical.items()
            )
            parts.append(f"categorical: {cats}")
        lines.append("- Parameter space: " + ". ".join(parts) + ".")
    if c.ground_truth is not None:
        g = c.ground_truth
        lines.append(f"- Ground truth: {g.regime} Uncertainty: {g.uncertainty}")
    return lines


def _scored_sets_lines(spec: BenchmarkSpec) -> list[str]:
    """The ``## Scored sets`` section: each scored set read by its coverage
    (ADR-0074 clause 2; the open-evaluation plan §4).

    One row per scored split with its case count and the coverage bins its
    cases fall in, so a legacy name (``test_interp``, ``probe``) is read as
    *within* or *beyond* the training box and how far from the nearest
    training point, or as *novel*. Returns ``[]`` when the benchmark cannot
    compute coverage (no case parameters, no declared box), so the section
    is absent rather than empty.
    """
    try:
        cov = spec.coverage()
    except ValueError:
        return []
    lines = [
        "## Scored sets",
        "",
        "Every split but `train` and `val` is scored, and a scored case is read "
        "by its coverage, not its split's name (ADR-0074): *within* the "
        "training design's declared box or *beyond* it, and its distance to "
        "the nearest training point in units of the training set's median "
        "nearest-neighbour spacing (one grid step on a grid), binned `≤ 1`, "
        "`1–2`, `> 2`; a case with an unseen categorical level or a changed "
        "constant is *novel* and shown apart. The box is the card's parameter "
        "space.",
        "",
        "| Set | Cases | Coverage |",
        "|---|---|---|",
    ]
    for split in spec.scored_splits:
        cases = spec.splits[split]
        counts: dict[str, int] = {}
        for case_id in cases:
            label = coverage_bin(cov[case_id])
            counts[label] = counts.get(label, 0) + 1
        bins = "; ".join(f"{label} ({n})" for label, n in counts.items())
        lines.append(f"| `{split}` | {len(cases)} | {bins} |")
    return lines


_COMPLIANCE_STATUS_LABEL = {
    "pass": "pass",
    "missing": "missing",
    "not_applicable": "not applicable",
    "never": "never",
}


def _compliance_lines(c: BenchmarkCard) -> list[str]:
    """The ``## Data standard`` section: the compliance table (ADR-0065
    follow-up 2, plan of 2026-11-08).

    One row per declared :class:`ComplianceRow`, in :data:`STANDARD_ITEMS`
    order; rows the card omits are not invented here (a registered benchmark
    covers every item by test). Returns ``[]`` when the card carries no rows,
    so the section is absent rather than empty. Shared by the landing page
    and the archive README, so the status has one source.
    """
    if not c.compliance:
        return []
    by_item = {row.item: row for row in c.compliance}
    required = ", ".join(STANDARD_ITEMS[k].lower() for k in REQUIRED_ITEMS)
    lines = [
        "## Data standard",
        "",
        "Where this benchmark's reference data stands against the platform's "
        "data standard. A benchmark admitted after 2026-10-01 must have a "
        f"{required} (ADR-0073 D14); a physical-test anchor and a "
        "second-solver reproduction are recorded where they exist and not "
        "required; the blind evaluation set is ADR-0074's. The benchmarks "
        "shipped before that date are grandfathered (ADR-0065): their rows "
        "show what exists, and a *missing* row is a fact about the data, not "
        "a verdict on it. Status: *pass* — the item exists and is recorded; "
        "*missing* — it does not exist yet; *not applicable* — the item has "
        "no meaning for this data; *never* — it cannot be produced.",
        "",
        "| Item | Status | Reason |",
        "|---|---|---|",
    ]
    for key, label in STANDARD_ITEMS.items():
        row = by_item.get(key)
        if row is None:
            continue
        status = _COMPLIANCE_STATUS_LABEL[row.status]
        lines.append(f"| {label} | {status} | {row.reason} |")
    return lines


def _is_restart_key(name: str) -> bool:
    """A restart-family key (ADR-0075 clause 5): a restart row or a
    composition row."""
    return name.startswith(("restart_", "compose_"))


def _partition_metrics(
    names: list[str],
) -> tuple[list[str], list[str], list[str], list[str], list[str]]:
    """Split metric keys into ``(props, rel_l2, rmse, qoi, restart)`` groups,
    each preserving the caller's first-seen order.

    ADR-0075 clause 6 (plan 3c): ``prop_*`` keys are the properties block,
    rendered before every accuracy group. ADR-0055 (amended 2026-08-15; pooled
    follow-up 2026-08-16): relative L2 is the headline metric — a single
    pooled space+time number per quantity. It leads the accuracy groups;
    physical-unit RMSE is the secondary group; ``qoi_*`` keys are the
    separate engineering axis. ADR-0075 clause 5 (plan 3b): ``restart_*``
    and ``compose_*`` keys are the restart family, rendered last. A key is a
    property iff it starts ``prop_``; a restart key iff it starts
    ``restart_`` or ``compose_``; relative-L2 iff it contains ``rel_l2``
    (covers ``rollout_rel_l2_displacement`` and any unit-suffixed registry
    variant); QoI iff it starts ``qoi_``; RMSE otherwise. (A per-frame-mean
    relative-L2 secondary existed briefly but was dropped 2026-08-16 — it
    blew up on zero-start aux fields and matched no reported convention.)
    """
    props = [m for m in names if m.startswith("prop_")]
    restart = [m for m in names if _is_restart_key(m)]
    rest = [m for m in names if not m.startswith("prop_") and not _is_restart_key(m)]
    rel_l2 = [m for m in rest if "rel_l2" in m]
    qoi = [m for m in rest if m.startswith("qoi_")]
    rmse = [m for m in rest if "rel_l2" not in m and not m.startswith("qoi_")]
    return props, rel_l2, rmse, qoi, restart


def _headline_metric(metrics: Mapping[str, float]) -> str:
    """The metric key quoted first in the docs-index one-liner: the pooled
    rollout relative-L2 displacement if present (ADR-0055 headline), else any
    relative-L2 key, else the first accuracy metric (pre-amendment behaviour,
    and the fallback for runs whose relative-L2 keys are not yet populated).
    A property (``prop_*``, ADR-0075) is never the headline."""
    rel_keys = [m for m in metrics if "rel_l2" in m]
    if rel_keys:
        rollout_disp = (m for m in rel_keys if "rollout" in m and "disp" in m)
        return next(rollout_disp, rel_keys[0])
    accuracy = (m for m in metrics if not m.startswith("prop_"))
    return next(accuracy, next(iter(metrics)))


def _baseline_line(spec: BenchmarkSpec) -> str:
    """Compact one-line results summary for the docs index (ADR-0033)."""
    if not spec.results:
        return "*no official baseline yet*"
    parts = []
    for r in spec.results:
        headline = ""
        for split in spec.splits:
            if split in r.metrics:
                key = _headline_metric(r.metrics[split])
                headline = f": {split} {key} {_fmt_value(r.metrics[split][key])}"
                break
        # Honest-not-silent (ADR-0033/0046): a provisional entry is tagged
        # here too, so the index never quietly reads as blessed.
        tag = _PROVISIONAL_TAG if r.provisional else ""
        parts.append(
            f"{r.label} ({r.family}, {r.run_date}, `{r.run_commit}`){tag}{headline}"
        )
    return "; ".join(parts)


def _quickstart_family(spec: BenchmarkSpec) -> tuple[str, str]:
    """The Quickstart's model family and its selection provenance (ADR-0046).

    Selection chain: the first blessed result's family (declaration order);
    else the first result's family, whether or not it is provisional; else
    ``spec.quickstart_family``. A provisional entry listed before a later
    blessed one still loses to the blessed one, since ``blessed_results``
    already preserves declaration order among blessed entries only.

    Returns
    -------
    tuple of str, str
        ``(family, provenance)`` with ``provenance`` one of ``"blessed"``,
        ``"provisional"``, or ``"default"``.
    """
    if spec.blessed_results:
        return spec.blessed_results[0].family, "blessed"
    if spec.results:
        return spec.results[0].family, "provisional"
    return spec.quickstart_family, "default"


def _col_label(split: str, key: str) -> str:
    """Compact ``split·quantity`` header for one results-registry column.

    Strips the scheme/aggregation prefixes and metric suffixes so the header
    reads as the physical quantity with a parenthesised unit, keeping only what
    distinguishes the column: ``rollout_rel_l2_disp`` @ ``test_interp`` ->
    ``interp·disp``; ``rollout_pos_rmse_mm`` -> ``interp·pos (mm)``;
    ``rollout_vm_rmse_mpa`` -> ``interp·vm (MPa)``; ``qoi_final_length_mae_mm``
    -> ``interp·final_length (mm)``; ``qoi_t_peak_vm_mae_ms`` ->
    ``interp·t_peak_vm (ms)``. A property key (ADR-0075) reads by its name
    in :data:`_PROPERTY_LABELS`, or with the ``prop_`` prefix stripped.
    """
    s = split.replace("test_", "")
    if key.startswith("prop_"):
        return f"{s}·{_PROPERTY_LABELS.get(key, key.removeprefix('prop_'))}"
    if _is_restart_key(key):
        # restart_a10_h20_rel_l2_displacement -> a10 h20 disp;
        # compose_T20_k2_position_rmse -> T20 k2 pos RMSE (mm). The relative
        # L2 forms read as the quantity alone, the RMSEs say so (restart keys
        # carry no unit suffix; positions are mm in the working frame).
        _, first, second, metric = key.split("_", 3)
        quantity = {
            "rel_l2_displacement": "disp",
            "rel_l2_aux": "aux",
            "rel_l2_state": "state",
            "position_rmse": "pos RMSE (mm)",
            "aux_rmse": "aux RMSE",
            "state_rmse": "state RMSE",
        }.get(metric, metric)
        return f"{s}·{first} {second} {quantity}"
    k = (
        key.replace("rollout_", "")
        .replace("one_step_", "1s·")
        .replace("qoi_", "")
        .replace("rel_l2_", "")
        .replace("_rmse", "")
        .replace("_mae", "")
    )
    for suffix, unit in (("_mm", " (mm)"), ("_mpa", " (MPa)"), ("_ms", " (ms)")):
        if k.endswith(suffix):
            k = k[: -len(suffix)] + unit
            break
    return f"{s}·{k}"


